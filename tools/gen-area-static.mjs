// The Area section renders its cards from AREA_DATA in JavaScript, which means
// 32 neighbourhood and landmark descriptions - the most locally relevant copy
// on the site - are absent from the HTML a crawler sees without running
// scripts. This emits that same copy as real markup inside the list container.
//
// It is not cloaking: the text is identical to what a visitor reads. The
// script clears the container on load and replaces it with the interactive
// version, so nobody sees it twice.
//
// Run after editing AREA_DATA:  node tools/gen-area-static.mjs

import { readFileSync, writeFileSync } from 'node:fs';

const FILE = new URL('../index.html', import.meta.url);
const START = '<!-- AREA_STATIC:START -->';
const END = '<!-- AREA_STATIC:END -->';

const html = readFileSync(FILE, 'utf8');

// Pull the object literal out by counting braces from `const AREA_DATA = {`.
const anchor = html.indexOf('const AREA_DATA = {');
if (anchor === -1) throw new Error('AREA_DATA not found in index.html');

const open = html.indexOf('{', anchor);
let depth = 0, end = -1;
for (let i = open; i < html.length; i++) {
  if (html[i] === '{') depth++;
  else if (html[i] === '}') {
    depth--;
    if (depth === 0) { end = i; break; }
  }
}
if (end === -1) throw new Error('Could not find the end of AREA_DATA');

// eslint-disable-next-line no-new-func
const AREA_DATA = new Function('return ' + html.slice(open, end + 1))();

const esc = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function section(heading, items) {
  const cards = items
    .map(
      (i) =>
        `        <li class="place-static">\n` +
        `          <h3>${esc(i.name)}</h3>\n` +
        `          <p>${esc(i.blurb)}</p>\n` +
        (i.tags && i.tags.length
          ? `          <p class="place-static-tags">${i.tags.map(esc).join(' · ')}</p>\n`
          : '') +
        `        </li>`
    )
    .join('\n');
  return `      <h3 class="place-static-head">${esc(heading)}</h3>\n` +
         `      <ul class="place-static-list">\n${cards}\n      </ul>`;
}

const block =
  `${START}\n` +
  `      <!-- Generated by tools/gen-area-static.mjs - do not hand-edit.\n` +
  `           Replaced by the interactive board on load; present so this copy\n` +
  `           is indexable without JavaScript. -->\n` +
  section('Neighborhoods across Tampa Bay and Sarasota', AREA_DATA.hoods) + '\n' +
  section('Landmarks and day trips', AREA_DATA.spots) + '\n' +
  `      ${END}`;

let out;
if (html.includes(START) && html.includes(END)) {
  out = html.slice(0, html.indexOf(START)) + block + html.slice(html.indexOf(END) + END.length);
} else {
  // First run: inject into the (otherwise empty) list container.
  const target = '<div class="area-list reveal" id="areaList" role="tabpanel" aria-labelledby="tab-hoods"></div>';
  if (!html.includes(target)) throw new Error('areaList container not found');
  out = html.replace(
    target,
    '<div class="area-list reveal" id="areaList" role="tabpanel" aria-labelledby="tab-hoods">\n' +
      block +
      '\n      </div>'
  );
}

writeFileSync(FILE, out);
console.log(
  `injected ${AREA_DATA.hoods.length} neighborhoods + ${AREA_DATA.spots.length} landmarks as static HTML`
);
